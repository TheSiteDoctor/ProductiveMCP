// Safe logging function that won't crash on EPIPE
function safeLog(message: string, data?: unknown): void {
  try {
    if (data) {
      console.error(message, data);
    } else {
      console.error(message);
    }
  } catch (err) {
    // Ignore logging errors
  }
}

// Handle tool calls
server.setRequestHandler(CallToolRequestSchema, async (request) => {
  const { name, arguments: args } = request.params;

  // Log incoming tool call
  safeLog("[MCP Tool Call]", {
    tool: name,
    args: JSON.stringify(args, null, 2),
  });

  try {
    const entry = toolRegistry[name];
    if (!entry) {
      safeLog("[MCP Tool Error]", { tool: name, error: "Unknown tool" });
      throw new Error(`Unknown tool: ${name}`);
    }

    const validated = entry.schema.parse(args);
    const result = await entry.handler(client, validated);
    safeLog("[MCP Tool Success]", { tool: name });
    return { content: [{ type: "text", text: result }] };
  } catch (error) {
    // Log detailed error information
    safeLog("[MCP Tool Error]", {
      tool: name,
      errorType: error instanceof Error ? error.constructor.name : typeof error,
      errorMessage: error instanceof Error ? error.message : String(error),
      stack: error instanceof Error ? error.stack : undefined,
    });

    const errorMessage =
      error instanceof Error ? error.message : "An unknown error occurred";
    return {
      content: [{ type: "text", text: `Error: ${errorMessage}` }],
      isError: true,
    };
  }
});

// Start server
async function main(): Promise<void> {
  const transport = new StdioServerTransport();

  // Handle transport errors gracefully
  process.stdout.on("error", (err) => {
    if (err.code === "EPIPE") {
      // Client disconnected, exit gracefully
      process.exit(0);
    }
  });

  process.stderr.on("error", (err) => {
    if (err.code === "EPIPE") {
      // Client disconnected, exit gracefully
      process.exit(0);
    }
  });

  await server.connect(transport);
  safeLog("Productive MCP server running on stdio");
}

main().catch((error) => {
  safeLog("Fatal error:", error);
  process.exit(1);
});
