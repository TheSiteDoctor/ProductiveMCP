/**
 * Build the `workflow_status` property for a tool's input schema.
 *
 * Returns an empty object when no statuses are configured, so the parameter is
 * omitted entirely rather than advertised and then rejected on every call —
 * which would fail the whole request, not just the status field.
 *
 * Spread into a schema's `properties`: `...workflowStatusProperty("...")`.
 */
function workflowStatusProperty(intro: string): Record<string, unknown> {
  if (WORKFLOW_STATUSES.length === 0) {
    return {};
  }
  return {
    workflow_status: {
      type: "string",
      enum: [...WORKFLOW_STATUSES],
      description: `${intro} Valid names come from productive.config.json (generated by \`npm run setup\`); an unrecognised name, or one belonging to a workflow your tasks don't use, returns an error listing the usable statuses.`,
    },
  };
}

